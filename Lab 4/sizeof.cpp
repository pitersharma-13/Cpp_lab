//Write a program to display the Size of theDifferent Datatypes in C.
#include<iostream>
using namespace std;
int main()
{
    cout<<"size of the  int data_type " <<sizeof(int) <<endl;
    cout<<"size of the  char data_type " <<sizeof(char) <<endl;
    cout<<"size of the  float data_type " <<sizeof(float) <<endl;
    cout<<"size of the  double data_type " <<sizeof(double) <<endl;    
    cout<<"size of the  long data_type " <<sizeof(long) <<endl;    
    cout<<"size of the  string data_type " <<sizeof(string) <<endl;    
    return 0;
}